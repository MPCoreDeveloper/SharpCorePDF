"""Builds the parity corpus and its manifest.

This module is invoked by ``make-fixtures.py --parity``; it is not a second entry point. The corpus is
generated rather than committed by hand so that every document can be described, regenerated and hashed.
The PDFs themselves stay checked in, because a test cannot depend on Python or pikepdf being installed.

The generator writes only original pages: no third-party document, font program or image is embedded.
The fixture files therefore carry the repository's MIT licence, which the manifest records per entry.
"""

from __future__ import annotations

import hashlib
import json
import shutil
from pathlib import Path

import pikepdf
from pikepdf import Array, Dictionary, Name, Pdf, String

A4_WIDTH = 595.276
A4_HEIGHT = 841.89
LETTER_WIDTH = 612.0
LETTER_HEIGHT = 792.0

CREATION_DATE = "D:20260101000000Z"
CREATOR = "SharpCorePDF parity corpus"
LICENCE = "MIT"

# A stable palette keeps the generated bytes independent of platform colour handling.
BLACK = (0.0, 0.0, 0.0)
BLUE = (0.05, 0.2, 0.75)
RED = (0.8, 0.1, 0.1)
GREY = (0.45, 0.45, 0.45)


def _literal(text: str) -> bytes:
    """Returns a PDF literal string for ``text`` in WinAnsi-compatible bytes."""
    raw = text.encode("cp1252", errors="replace")
    result = bytearray(b"(")

    for byte in raw:
        if byte in b"()\\":
            result.extend(b"\\")
            result.append(byte)
        elif byte < 32 or byte > 126:
            result.extend(f"\\{byte:03o}".encode("ascii"))
        else:
            result.append(byte)

    return bytes(result + b")")


def _standard_font(pdf: Pdf, base_font: str) -> Dictionary:
    """Returns one of the standard fourteen fonts as a page resource."""
    return pdf.make_indirect(
        Dictionary(
            Type=Name.Font,
            Subtype=Name.Type1,
            BaseFont=Name("/" + base_font),
            Encoding=Name.WinAnsiEncoding,
        )
    )


def _fonts(pdf: Pdf) -> Dictionary:
    return Dictionary(
        F1=_standard_font(pdf, "Helvetica"),
        F2=_standard_font(pdf, "Courier"),
        F3=_standard_font(pdf, "Times-Roman"),
    )


def add_page(
    pdf: Pdf,
    width: float = A4_WIDTH,
    height: float = A4_HEIGHT,
    rotate: int = 0,
) -> tuple[object, list[bytes]]:
    """Adds a blank page and returns it with the operations that will form its content stream."""
    page = pdf.add_blank_page(page_size=(width, height))
    page.MediaBox = Array([0, 0, width, height])
    page.Resources = Dictionary(Font=_fonts(pdf))

    if rotate:
        page.Rotate = rotate

    return page, []


def text(
    operations: list[bytes],
    value: str,
    x: float,
    y: float,
    size: float = 10,
    font: str = "F2",
    colour: tuple[float, float, float] = BLACK,
) -> None:
    """Appends one text-showing operation at a PDF user-space baseline."""
    red, green, blue = colour
    operations.append(
        f"BT /{font} {size:g} Tf {red:g} {green:g} {blue:g} rg 1 0 0 1 {x:g} {y:g} Tm ".encode("ascii")
        + _literal(value)
        + b" Tj ET"
    )


def line(
    operations: list[bytes],
    x1: float,
    y1: float,
    x2: float,
    y2: float,
    width: float = 1,
    colour: tuple[float, float, float] = BLACK,
) -> None:
    """Appends a stroked line."""
    red, green, blue = colour
    operations.append(
        f"{red:g} {green:g} {blue:g} RG {width:g} w {x1:g} {y1:g} m {x2:g} {y2:g} l S".encode("ascii")
    )


def rectangle(
    operations: list[bytes],
    x: float,
    y: float,
    width: float,
    height: float,
    stroke: tuple[float, float, float] = BLACK,
    fill: tuple[float, float, float] | None = None,
) -> None:
    """Appends a filled and/or stroked rectangle."""
    red, green, blue = stroke
    paint = "S"

    if fill is not None:
        fill_red, fill_green, fill_blue = fill
        operations.append(
            f"{fill_red:g} {fill_green:g} {fill_blue:g} rg".encode("ascii")
        )
        paint = "B"

    operations.append(
        f"{red:g} {green:g} {blue:g} RG {x:g} {y:g} {width:g} {height:g} re {paint}".encode("ascii")
    )


def finish(pdf: Pdf, page: object, operations: list[bytes]) -> None:
    """Writes the accumulated operations as the page's content stream."""
    page.Contents = pdf.make_stream(b"\n".join(operations))


def set_metadata(pdf: Pdf, title: str, subject: str | None = None) -> None:
    """Writes deterministic document information into the file."""
    pdf.docinfo["/Title"] = String(title)
    pdf.docinfo["/Author"] = String(CREATOR)
    pdf.docinfo["/Creator"] = String(CREATOR)
    pdf.docinfo["/Producer"] = String("SharpCorePDF fixture generator")
    pdf.docinfo["/CreationDate"] = String(CREATION_DATE)
    pdf.docinfo["/ModDate"] = String(CREATION_DATE)

    if subject is not None:
        pdf.docinfo["/Subject"] = String(subject)


def set_xmp(pdf: Pdf, title: str) -> None:
    """Writes a small XMP packet with a stable title and creator tool."""
    with pdf.open_metadata(set_pikepdf_as_editor=False) as metadata:
        metadata["dc:title"] = title
        metadata["dc:creator"] = [CREATOR]
        metadata["xmp:CreatorTool"] = CREATOR
        metadata["xmp:CreateDate"] = "2026-01-01T00:00:00Z"
        metadata["xmp:ModifyDate"] = "2026-01-01T00:00:00Z"
        metadata["xmp:MetadataDate"] = "2026-01-01T00:00:00Z"
        metadata["pdf:Producer"] = "SharpCorePDF fixture generator"


def set_outline(pdf: Pdf, entries: list[tuple[str, object]]) -> None:
    """Writes a flat outline whose entries point at the supplied pages."""
    if not entries:
        return

    outlines = pdf.make_indirect(Dictionary(Type=Name.Outlines))
    items = []

    for title, page in entries:
        item = pdf.make_indirect(
            Dictionary(
                Title=String(title),
                Parent=outlines,
                Dest=Array([page.obj, Name.Fit]),
            )
        )
        items.append(item)

    for index, item in enumerate(items):
        if index > 0:
            item.Prev = items[index - 1]
        if index + 1 < len(items):
            item.Next = items[index + 1]

    outlines.First = items[0]
    outlines.Last = items[-1]
    outlines.Count = len(items)
    pdf.Root.Outlines = outlines


def set_page_labels(pdf: Pdf, style: str = "D") -> None:
    """Gives every page a decimal label starting at one."""
    pdf.Root.PageLabels = pdf.make_indirect(
        Dictionary(Nums=Array([0, Dictionary(S=Name("/" + style))]))
    )


def add_uri_link(pdf: Pdf, page: object, uri: str, box: list[float]) -> None:
    """Adds a URI link annotation to a page."""
    annotation = pdf.make_indirect(
        Dictionary(
            Type=Name.Annot,
            Subtype=Name.Link,
            Rect=Array(box),
            Border=Array([0, 0, 0]),
            A=Dictionary(S=Name.URI, URI=String(uri)),
        )
    )
    existing = page.obj.get("/Annots") or Array()
    existing.append(annotation)
    page.Annots = existing


def add_internal_link(pdf: Pdf, page: object, target: object, box: list[float]) -> None:
    """Adds a link annotation whose destination is a page in the same document."""
    annotation = pdf.make_indirect(
        Dictionary(
            Type=Name.Annot,
            Subtype=Name.Link,
            Rect=Array(box),
            Border=Array([0, 0, 0]),
            Dest=Array([target.obj, Name.Fit]),
        )
    )
    existing = page.Annots if "Annots" in page else Array()
    existing.append(annotation)
    page.Annots = existing


def add_image(pdf: Pdf, page: object, x: float, y: float, width: float, height: float) -> bytes:
    """Registers a deterministic two by two RGB image and returns the operation that draws it."""
    import zlib

    samples = bytes([220, 40, 40, 250, 180, 30, 30, 80, 200, 20, 20, 20])
    image = pikepdf.Stream(pdf, zlib.compress(samples))
    image.Type = Name.XObject
    image.Subtype = Name.Image
    image.Width = 2
    image.Height = 2
    image.ColorSpace = Name.DeviceRGB
    image.BitsPerComponent = 8
    image.Filter = Name.FlateDecode
    image = pdf.make_indirect(image)

    page.Resources.XObject = Dictionary(Im1=image)
    return f"q {width:g} 0 0 {height:g} {x:g} {y:g} cm /Im1 Do Q".encode("ascii")




def body_lines(prefix: str, count: int, start: int = 1) -> list[str]:
    """Returns a set of deterministic body lines that are easy to find in an extraction result."""
    return [
        f"{prefix} {number:02d}: the quick brown fox jumps over the lazy dog."
        for number in range(start, start + count)
    ]


def build_corpus_document(kind: str, variant: int) -> tuple[Pdf, int, list[str], str]:
    """Builds one born-digital document of the requested archetype."""
    pdf = Pdf.new()
    features = ["text"]
    pages = []
    summary = ""

    if kind == "single-column":
        page_count = 1 + (variant % 3)
        for page_number in range(1, page_count + 1):
            page, operations = add_page(pdf)
            text(operations, f"Single column report {variant:02d}", 72, 790, 16, "F1", BLUE)
            for index, value in enumerate(body_lines(f"Page {page_number}", 24)):
                text(operations, value, 72, 755 - (index * 26), 10)
            finish(pdf, page, operations)
            pages.append(page)
        summary = f"Single column report {variant:02d}"
        features.append("single-column")

    elif kind == "two-column":
        page_count = 2
        for page_number in range(1, page_count + 1):
            page, operations = add_page(pdf)
            text(operations, f"Two column report {variant:02d}", 72, 790, 16, "F1", BLUE)
            text(operations, "Left column", 72, 760, 11, "F1", RED)
            text(operations, "Right column", 330, 760, 11, "F1", RED)
            for index, value in enumerate(body_lines(f"L{page_number}", 18)):
                text(operations, value, 72, 735 - (index * 24), 9)
            for index, value in enumerate(body_lines(f"R{page_number}", 18)):
                text(operations, value, 330, 735 - (index * 24), 9)
            finish(pdf, page, operations)
            pages.append(page)
        summary = f"Two column report {variant:02d}"
        features.extend(["two-column", "reading-order"])

    elif kind == "three-column":
        page, operations = add_page(pdf, LETTER_WIDTH, LETTER_HEIGHT)
        text(operations, f"Three column brief {variant:02d}", 48, 745, 15, "F1", BLUE)
        for column, x in enumerate((48, 240, 432)):
            text(operations, f"Column {column + 1}", x, 715, 10, "F1", RED)
            for index, value in enumerate(body_lines(f"C{column + 1}", 16)):
                text(operations, value, x, 690 - (index * 22), 8)
        finish(pdf, page, operations)
        pages.append(page)
    elif kind == "rotated":
        page, operations = add_page(pdf, rotate=90)
        text(operations, f"Rotated notice {variant:02d}", 72, 760, 15, "F1", BLUE)
        for index, value in enumerate(body_lines("Rotated", 20)):
            text(operations, value, 72, 730 - (index * 26), 10)
        finish(pdf, page, operations)
        pages.append(page)
        summary = f"Rotated notice {variant:02d}"
        features.extend(["rotation", "single-column"])

    elif kind == "landscape":
        page, operations = add_page(pdf, A4_HEIGHT, A4_WIDTH)
        text(operations, f"Landscape schedule {variant:02d}", 60, 540, 16, "F1", BLUE)
        for index, value in enumerate(body_lines("Landscape", 12)):
            text(operations, value, 60, 500 - (index * 24), 10)
        finish(pdf, page, operations)
        pages.append(page)
        summary = f"Landscape schedule {variant:02d}"
        features.extend(["landscape", "single-column"])

    elif kind == "unicode":
        page, operations = add_page(pdf)
        text(operations, f"Décompte numéro {variant:02d}", 72, 770, 16, "F1", BLUE)
        lines = [
            "Veuillez trouver ci-joint le décompte de l’immeuble.",
            "Café, naïve, façade, élève, garçon, déjà vu.",
            "Größe, Straße, Müller, schön, über, Zürich.",
            "Ação, coração, informação, São Paulo, não.",
            "Français: où, être, Noël, aiguë, ambiguïté.",
        ]
        for index, value in enumerate(lines):
            text(operations, value, 72, 730 - (index * 28), 11)
        finish(pdf, page, operations)
        pages.append(page)
        summary = f"Décompte numéro {variant:02d}"
        features.extend(["unicode", "accents", "winansi"])

    elif kind == "bookmarks":
        for page_number in range(1, 4):
            page, operations = add_page(pdf)
            text(operations, f"Chapter {page_number} of variant {variant:02d}", 72, 780, 17, "F1", BLUE)
            for index, value in enumerate(body_lines(f"Chapter {page_number}", 12)):
                text(operations, value, 72, 745 - (index * 26), 10)
            finish(pdf, page, operations)
            pages.append(page)

        set_outline(pdf, [(f"Chapter {number}", page) for number, page in enumerate(pages, start=1)])
        set_page_labels(pdf)
        summary = f"Bookmarked report {variant:02d}"
        features.extend(["outline", "page-labels"])

    elif kind == "metadata":
        page, operations = add_page(pdf)
        text(operations, f"Metadata record {variant:02d}", 72, 780, 17, "F1", BLUE)
        for index, value in enumerate(body_lines("Metadata", 10)):
            text(operations, value, 72, 745 - (index * 26), 10)
        finish(pdf, page, operations)
        pages.append(page)
        set_metadata(pdf, f"Metadata record {variant:02d}", f"Parity metadata variant {variant}")
        set_xmp(pdf, f"Metadata record {variant:02d}")
        summary = f"Metadata record {variant:02d}"
    elif kind == "links":
        first, first_operations = add_page(pdf)
        text(first_operations, f"Link collection {variant:02d}", 72, 780, 17, "F1", BLUE)
        text(first_operations, "External link: example.org", 72, 735, 11, "F1", BLUE)
        text(first_operations, "Internal link: page two", 72, 705, 11, "F1", BLUE)
        finish(pdf, first, first_operations)

        second, second_operations = add_page(pdf)
        text(second_operations, f"Link target {variant:02d}", 72, 780, 17, "F1", BLUE)
        text(second_operations, "The destination page of the internal link.", 72, 735, 11)
        finish(pdf, second, second_operations)

        add_uri_link(pdf, first, f"https://example.org/parity/{variant:02d}", [72, 728, 300, 744])
        add_internal_link(pdf, first, second, [72, 698, 300, 714])
        pages.extend([first, second])
        summary = f"Link collection {variant:02d}"
        features.extend(["hyperlinks", "uri", "internal-destination"])

    elif kind == "image":
        page, operations = add_page(pdf)
        text(operations, f"Illustrated note {variant:02d}", 72, 780, 17, "F1", BLUE)
        text(operations, "A two by two RGB image is drawn below the caption.", 72, 745, 10)
        operations.append(add_image(pdf, page, 72, 600, 160, 100))
        finish(pdf, page, operations)
        pages.append(page)
        summary = f"Illustrated note {variant:02d}"
        features.extend(["image", "device-rgb", "flate"])

    elif kind == "table":
        page, operations = add_page(pdf, LETTER_WIDTH, LETTER_HEIGHT)
        text(operations, f"Table extract {variant:02d}", 48, 750, 16, "F1", BLUE)
        top = 720
        row_height = 24
        for row in range(14):
            rectangle(operations, 48, top - (row * row_height), 516, row_height, GREY)
            for column in range(4):
                text(
                    operations,
                    f"R{row + 1:02d}C{column + 1}",
                    58 + (column * 128),
                    top - (row * row_height) - 16,
                    8,
                )
        finish(pdf, page, operations)
        pages.append(page)
        summary = f"Table extract {variant:02d}"
        features.extend(["table", "rules", "grid"])

    elif kind == "dense":
        page_count = 2 + (variant % 2)
        for page_number in range(1, page_count + 1):
            page, operations = add_page(pdf)
            text(operations, f"Dense report {variant:02d} page {page_number}", 48, 800, 15, "F1", BLUE)
            for index, value in enumerate(body_lines(f"D{page_number}", 48)):
                text(operations, value, 48, 775 - (index * 15), 7)
            finish(pdf, page, operations)
            pages.append(page)
        summary = f"Dense report {variant:02d}"
        features.extend(["dense-text", "single-column"])

    else:
        raise ValueError(f"Unknown corpus archetype: {kind}")

    pdf.docinfo["/Title"] = String(summary)
    pdf.docinfo["/Author"] = String(CREATOR)
    pdf.docinfo["/Creator"] = String(CREATOR)
    pdf.docinfo["/Producer"] = String("SharpCorePDF fixture generator")
    pdf.docinfo["/CreationDate"] = String(CREATION_DATE)
    pdf.docinfo["/ModDate"] = String(CREATION_DATE)

    return pdf, len(pages), features, summary




def save(pdf: Pdf, path: Path) -> None:
    """Writes the PDF with a reproducible trailer identifier."""
    path.parent.mkdir(parents=True, exist_ok=True)
    pdf.save(path, deterministic_id=True)


