def digest(path: Path) -> str:
    """Returns the SHA-256 of a file as lower-case hexadecimal."""
    return hashlib.sha256(path.read_bytes()).hexdigest()


def entry(root: Path, path: Path, kind: str, description: str) -> dict[str, object]:
    """Describes one generated file for the manifest and the corpus test."""
    return {
        "path": path.relative_to(root).as_posix(),
        "kind": kind,
        "description": description,
        "source": "generated by docs/tools/make-fixtures.py --parity",
        "licence": LICENCE,
        "sha256": digest(path),
        "bytes": path.stat().st_size,
    }


def write_manifest(root: Path, files: list[dict[str, object]]) -> None:
    """Writes the manifest with stable ordering and no environment-specific data."""
    manifest = {
        "schema": 1,
        "generator": "docs/tools/make-fixtures.py --parity",
        "source": "Original pages generated by the repository; no third-party PDF, font or image.",
        "licence": LICENCE,
        "coordinateSystem": "PDF user space, origin bottom-left, measured in points",
        "files": sorted(files, key=lambda item: item["path"]),
    }

    path = root / "manifest.json"
    path.write_text(
        json.dumps(manifest, indent=2, sort_keys=True, ensure_ascii=False) + "\n",
        encoding="utf-8",
    )


