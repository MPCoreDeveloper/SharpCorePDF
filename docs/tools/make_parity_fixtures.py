def _annotation(
    pdf: Pdf,
    page: object,
    subtype: str,
    box: list[float],
    contents: str | None = None,
    colour: list[float] | None = None,
    **extra: object,
) -> Dictionary:
    """Creates one annotation and appends it to a page."""
    entries = {
        "/Type": Name.Annot,
        "/Subtype": Name("/" + subtype),
        "/Rect": Array(box),
        "/F": 4,
    }

    if contents is not None:
        entries["/Contents"] = String(contents)
    if colour is not None:
        entries["/C"] = Array(colour)

    entries.update({("/" + key): value for key, value in extra.items()})
    annotation = pdf.make_indirect(Dictionary(entries))
    page.Annots.append(annotation)
    return annotation


