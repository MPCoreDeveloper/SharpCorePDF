def make_pdfa_candidates(root: Path) -> list[dict[str, object]]:
    """Creates the three PDF/A conversion candidates; none claims conformance."""
    folder = root / "pdfa"
    files: list[dict[str, object]] = []

    for part, name in ((1, "PdfA1bCandidate"), (2, "PdfA2bCandidate"), (3, "PdfA3bCandidate")):
        pdf = Pdf.new()
        page, operations = add_page(pdf)
        text(operations, f"PDF/A-{part}b candidate", 72, 780, 17, "F1", BLUE)
        for index, value in enumerate(body_lines("Archive", 8)):
            text(operations, value, 72, 745 - (index * 26), 10)
        finish(pdf, page, operations)
        set_metadata(pdf, f"PDF/A-{part}b candidate", "Input for the Phase 4 conversion tests")
        set_xmp(pdf, f"PDF/A-{part}b candidate")

        with pdf.open_metadata(set_pikepdf_as_editor=False) as metadata:
            metadata["pdfaid:part"] = str(part)
            metadata["pdfaid:conformance"] = "B"

        path = folder / f"{name}.pdf"
