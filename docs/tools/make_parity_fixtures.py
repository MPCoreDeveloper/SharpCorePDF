def make_labelled(root: Path) -> list[dict[str, object]]:
    """Creates the curated reading-order subset and one label file per document."""
    files: list[dict[str, object]] = []
    label_folder = root / "labelled"

    for identifier, blocks in LABELLED_DOCUMENTS:
        pdf = Pdf.new()
        page, operations = add_page(pdf, LETTER_WIDTH, LETTER_HEIGHT)
        text(operations, f"Labelled document: {identifier}", 72, 750, 14, "F1", BLUE)

        page_labels = []
        order = 0
        y = 700
        current_group = None

        for group, x, lines in blocks:
            if current_group is not None and group != current_group:
                y -= 18
            current_group = group

            for value in lines:
                order += 1
                text(operations, value, x, y, 10)
                width = len(value) * 6.0
                box = [x, y - 2, x + width, y + 8]
                characters = []

                for index, character in enumerate(value):
                    character_x = x + (index * 6.0)
                    characters.append(
                        {
                            "text": character,
                            "box": [character_x, y - 2, character_x + 6.0, y + 8],
                        }
                    )

                page_labels.append(
                    {
                        "id": f"{identifier}-{order:02d}",
                        "group": group,
                        "order": order,
                        "text": value,
                        "baseline": [x, y],
                        "box": box,
                        "characters": characters,
                    }
                )
                y -= 20

        finish(pdf, page, operations)
        pdf_path = label_folder / f"{identifier}.pdf"
        save(pdf, pdf_path)

        labels = {
            "schema": 1,
            "document": pdf_path.name,
            "provenance": "curated by the repository maintainers; not produced by the library",
            "coordinateSystem": "PDF user space, origin bottom-left, in points",
            "boxConvention": "baseline box: y - 2 to y + 8 for 10 pt Courier",
            "pages": [
                {
                    "page": 1,
                    "width": LETTER_WIDTH,
                    "height": LETTER_HEIGHT,
                    "blocks": page_labels,
                }
            ],
        }
        label_path = label_folder / f"{identifier}.json"
        label_path.write_text(
            json.dumps(labels, indent=2, sort_keys=True, ensure_ascii=False) + "\n",
            encoding="utf-8",
        )

        pdf_entry = entry(root, pdf_path, "labelled", f"Labelled reading-order document {identifier}")
        pdf_entry.update(
            {
                "id": identifier,
                "pages": 1,
                "features": ["labelled", "reading-order", "courier", "text"],
                "labels": label_path.relative_to(root).as_posix(),
            }
        )
        files.append(pdf_entry)
        files.append(entry(root, label_path, "label", f"Reading-order labels for {identifier}"))
        print(f"wrote {pdf_path} and {label_path}")

    return files


def make_images(root: Path) -> list[dict[str, object]]:
    """Creates the supported and refused image variants the image contract names."""
    from PIL import Image

    folder = root / "images"
    files: list[dict[str, object]] = []

    def gradient(mode: str = "RGB", size: tuple[int, int] = (64, 40)) -> Image.Image:
        image = Image.new(mode, size)
        pixels = image.load()

        for y in range(size[1]):
            for x in range(size[0]):
                red = int(255 * x / max(1, size[0] - 1))
                green = int(255 * y / max(1, size[1] - 1))
                blue = (x * 7 + y * 11) % 256
                pixels[x, y] = (red, green, blue) if mode == "RGB" else (red, green, blue, 128)

        return image

    def record(path: Path, features: list[str], width: int | None = None, height: int | None = None) -> None:
        value = entry(root, path, "image", path.name)
        value.update({"features": features})

        if width is not None:
            value.update({"width": width, "height": height})

        files.append(value)
        print(f"wrote {path}")

    rgb = gradient()

    path = folder / "png-rgb.png"
    rgb.save(path, format="PNG")
    record(path, ["png", "rgb", "opaque"], rgb.width, rgb.height)

    rgba = gradient("RGBA")
    path = folder / "png-rgba.png"
    rgba.save(path, format="PNG")
    record(path, ["png", "rgba", "alpha"], rgba.width, rgba.height)

    palette = rgb.convert("P", palette=Image.Palette.ADAPTIVE, colors=8)
    palette.info["transparency"] = 0
    path = folder / "png-palette-trns.png"
    palette.save(path, format="PNG", transparency=0)
    record(path, ["png", "palette", "trns"], palette.width, palette.height)

    sixteen = Image.new("I;16", (32, 24))
