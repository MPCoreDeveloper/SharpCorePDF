def _form_pdf() -> tuple[Pdf, object, Dictionary]:
    """Creates a one-page document with an empty AcroForm and returns its font dictionary."""
    pdf = Pdf.new()
    page, operations = add_page(pdf, LETTER_WIDTH, LETTER_HEIGHT)
    text(operations, "AcroForm fixture", 72, 740, 16, "F1", BLUE)
    finish(pdf, page, operations)

    helvetica = _standard_font(pdf, "Helvetica")
    acro_form = pdf.make_indirect(
        Dictionary(
            Fields=Array(),
            DA=String("/Helv 10 Tf 0 g"),
            DR=Dictionary(Font=Dictionary(Helv=helvetica)),
            NeedAppearances=False,
        )
    )
    pdf.Root.AcroForm = acro_form
    page.Annots = Array()
    return pdf, page, Dictionary(Helv=helvetica)


def _add_widget(
    pdf: Pdf,
    page: object,
    acro_form: Dictionary,
    name: str,
    field_type: str,
    box: list[float],
    value: str | None = None,
    flags: int = 0,
) -> Dictionary:
    """Adds a simple widget and its terminal field to the AcroForm."""
    entries = {
        "/Type": Name.Annot,
        "/Subtype": Name.Widget,
        "/FT": Name("/" + field_type),
        "/T": String(name),
        "/Rect": Array(box),
        "/P": page.obj,
        "/F": 4,
        "/Ff": flags,
        "/DA": String("/Helv 10 Tf 0 g"),
    }

    if value is not None:
        entries["/V"] = String(value)

    widget = pdf.make_indirect(Dictionary(entries))
    page.Annots.append(widget)
    acro_form.Fields.append(widget)
    return widget


